// Generate a human-readable reference: LKY-YYYYMM-NNNNN
export function generateReference(id = '') {
  const now = new Date();
  const ym = `${now.getFullYear()}${String(now.getMonth() + 1).padStart(2, '0')}`;
  const suffix = id ? id.replace(/\D/g, '').slice(-5).padStart(5, '0') : Math.floor(Math.random() * 99999).toString().padStart(5, '0');
  return `LKY-${ym}-${suffix}`;
}

